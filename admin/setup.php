<?php
/**
 * One-time installer.
 *
 * The gate is a SHA-256 digest of a 48-character random token: only the digest
 * lives in this file, so the repository never contains a usable secret. Once
 * config.php exists this endpoint is dead (410), so it cannot be reused to
 * reset the administrator account.
 */
declare(strict_types=1);

require __DIR__ . '/lib/bootstrap.php';

$SETUP_TOKEN_SHA256='ba7f89b7' . '6df2b736' . 'c59b70de' . '1ca88c97' . '793067f0' . 'ed127401' . '0302c452' . 'f0b76b0f';

security_headers(true);

if (is_installed()) {
    json_out(['error' => 'already_installed'], 410);
}

require_method('POST');

$provided = $_SERVER['HTTP_X_SETUP_TOKEN'] ?? '';
if (!is_string($provided) || $provided === ''
    || !hash_equals($SETUP_TOKEN_SHA256, hash('sha256', $provided))) {
    usleep(400000);
    json_out(['error' => 'forbidden'], 403);
}

if (!rate_limit('setup:' . ip_hash(), 5, 3600)) {
    json_out(['error' => 'rate_limited'], 429);
}

$body = read_json_body(2048);
$username = clean_str($body['username'] ?? '', 32);
$password = is_string($body['password'] ?? null) ? $body['password'] : '';

if (!preg_match('/^[a-z0-9._-]{3,32}$/', $username)) {
    json_out(['error' => 'invalid_username', 'detail' => 'lowercase letters, digits, dot, dash, underscore (3-32)'], 422);
}
$problem = password_problem($password);
if ($problem !== null) {
    json_out(['error' => 'weak_password', 'detail' => $problem], 422);
}

$secret = bin2hex(random_bytes(32));
$config = "<?php\n// Generated by setup. Never commit this file.\nreturn " . var_export([
    'app_secret' => $secret,
    'installed_at' => time(),
    'installed_by' => $username,
], true) . ";\n";

$target = STORAGE . '/config.php';
$tmp = $target . '.tmp';
if (file_put_contents($tmp, $config, LOCK_EX) === false) {
    json_out(['error' => 'storage_unwritable'], 500);
}
@chmod($tmp, 0600);
if (!@rename($tmp, $target)) {
    @unlink($tmp);
    json_out(['error' => 'storage_unwritable'], 500);
}

$pdo = db();
$stmt = $pdo->prepare('INSERT INTO users (username, pass_hash, created_at) VALUES (?, ?, ?)');
$stmt->execute([
    $username,
    password_hash($password, PASSWORD_BCRYPT, ['cost' => 12]),
    time(),
]);

audit('install', 'admin account created', $username);

json_out(['ok' => true, 'user' => $username], 201);
